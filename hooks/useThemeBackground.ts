'use client';

import { useTheme } from 'next-themes';
import { useState, useEffect, useMemo, useRef } from 'react';

interface ThemeBackgroundOptions {
  /** Static plate (contours only) — painted as a CSS background-image. */
  lightImage: string;
  darkImage: string;
  /**
   * Animated glow (reverse-glow overlay only) — fetched + inlined over the
   * plate. ONE themeless file: overlay paths use var(--surface-page) so the
   * CSS custom property resolves from the page's html.dark class at runtime.
   * No refetch needed on theme toggle.
   */
  glow: string;
  /** Optional portrait (mobile) plate/glow — only home sets these. */
  lightImageMobile?: string;
  darkImageMobile?: string;
  glowMobile?: string;
  mobileBreakpoint?: number;
}

interface ThemeBackgroundResult {
  mounted: boolean;
  isMobile: boolean;
  resolvedTheme: string | undefined;
  /**
   * Raw static plate URLs (NOT JS-resolved). The component paints both as CSS
   * background-images on `dark:hidden` / `hidden dark:block` siblings so the
   * correct plate is picked by the `.dark` class from SSR and only the visible
   * one is fetched — no SSR-light-then-dark double download, no flash.
   */
  lightPlate: string;
  darkPlate: string;
  /** Portrait (mobile) plate URLs — present only for pages with mobile variants. */
  lightPlateMobile?: string;
  darkPlateMobile?: string;
  /**
   * Resolved animated glow URL — inlined over the plate. Themeless: one file
   * handles both light and dark via var(--surface-page). Only isMobile changes
   * which file is returned (mobile portrait variant vs. desktop landscape).
   * Theme toggle does NOT trigger a refetch.
   */
  glowSrc: string;
  isDark: boolean;
}

/**
 * Per-page backdrop plate presets (backdrop engine v3). Each page maps to a
 * fixed landscape contour plate split into THREE assets:
 *   <page>_<theme>_plate.svg — static contours, painted as a CSS background
 *     (theme-split so the browser fetches only the visible one).
 *   {page}_glow.svg — the animated reverse-glow overlay, fetched + inlined on
 *     top. ONE themeless file per orientation: overlay paths carry
 *     style="stroke:var(--surface-page)" so CSS resolves the correct colour
 *     (#f7f4ec light / #1a1814 dark) from the html.dark class. Re-theming is
 *     instant — no refetch, no flash.
 *
 * Files are generated by scripts/build-plates.mjs into public/images/plates/.
 */
export type PlatePage =
  | 'home'
  | 'portfolio'
  | 'ej'
  | 'resume'
  | 'interests'
  | 'notFound';

const platePreset = (page: PlatePage) => {
  return {
    lightImage: `/images/plates/${page}_light_plate.svg`,
    darkImage: `/images/plates/${page}_dark_plate.svg`,
    glow: `/images/plates/${page}_glow.svg`,
  } as const;
};

export const PLATE_PRESETS = {
  home: {
    ...platePreset('home'),
    // Portrait (mobile) plate/glow for the home page — Big Sur iqr3 portrait.
    lightImageMobile: '/images/plates/home_light_plate_mobile.svg',
    darkImageMobile: '/images/plates/home_dark_plate_mobile.svg',
    glowMobile: '/images/plates/home_glow_mobile.svg',
  },
  portfolio: platePreset('portfolio'),
  ej: platePreset('ej'),
  resume: platePreset('resume'),
  interests: platePreset('interests'),
  notFound: platePreset('notFound'),
} as const;

/**
 * Hook for managing theme-aware backgrounds with mobile detection.
 */
export function useThemeBackground(options: ThemeBackgroundOptions): ThemeBackgroundResult {
  const { resolvedTheme } = useTheme();
  const [mounted, setMounted] = useState(false);
  const [isMobile, setIsMobile] = useState(false);

  const mobileBreakpoint = options.mobileBreakpoint ?? 768;
  const lastWidthRef = useRef<number | null>(null);
  const debounceTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    setMounted(true);

    // Synchronous initial check on mount.
    lastWidthRef.current = window.innerWidth;
    setIsMobile(window.innerWidth < mobileBreakpoint);

    const handleResize = () => {
      const currentWidth = window.innerWidth;
      // URL-bar collapse is height-only — width stays the same.
      // Bail out immediately to avoid re-rendering the backdrop.
      if (currentWidth === lastWidthRef.current) return;

      // Width actually changed — debounce the state update by ~150 ms so
      // rapid resize drags only trigger one re-render.
      lastWidthRef.current = currentWidth;
      if (debounceTimerRef.current !== null) {
        clearTimeout(debounceTimerRef.current);
      }
      debounceTimerRef.current = setTimeout(() => {
        setIsMobile(currentWidth < mobileBreakpoint);
      }, 150);
    };

    window.addEventListener('resize', handleResize);

    return () => {
      window.removeEventListener('resize', handleResize);
      if (debounceTimerRef.current !== null) {
        clearTimeout(debounceTimerRef.current);
      }
    };
  }, [mobileBreakpoint]);

  const isDark = mounted && resolvedTheme === 'dark';

  // The plate is no longer JS-resolved: both URLs are handed to the component,
  // which paints them on theme-gated (`dark:hidden` / `hidden dark:block`)
  // siblings so the browser fetches only the visible one and SSR HTML already
  // references the correct theme.
  const lightPlate = options.lightImage;
  const darkPlate = options.darkImage;

  // The glow is themeless: one file per orientation (desktop / mobile portrait).
  // Only isMobile determines which file to use — theme does NOT change the src.
  // var(--surface-page) in the inlined SVG resolves the correct bg colour live.
  const glowSrc = useMemo(() => {
    const hasMobileGlow = !!options.glowMobile;
    if (hasMobileGlow && isMobile) {
      return options.glowMobile!;
    }
    return options.glow;
  }, [isMobile, options.glow, options.glowMobile]);

  return {
    mounted,
    isMobile,
    resolvedTheme,
    lightPlate,
    darkPlate,
    lightPlateMobile: options.lightImageMobile,
    darkPlateMobile: options.darkImageMobile,
    glowSrc,
    isDark,
  };
}
