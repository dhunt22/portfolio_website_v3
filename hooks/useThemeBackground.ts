'use client';

import { useTheme } from 'next-themes';
import { useState, useEffect, useMemo } from 'react';

interface ThemeBackgroundOptions {
  /** Static plate (contours only) — painted as a CSS background-image. */
  lightImage: string;
  darkImage: string;
  /** Animated glow (comet system only) — fetched + inlined over the plate. */
  glowLight: string;
  glowDark: string;
  mobileBreakpoint?: number;
}

interface ThemeBackgroundResult {
  mounted: boolean;
  isMobile: boolean;
  resolvedTheme: string | undefined;
  backgroundImage: string;
  /** Resolved static plate URL (light or dark) without the url() wrapper. */
  plateSrc: string;
  /** Resolved animated glow URL (light or dark) — inlined over the plate. */
  glowSrc: string;
  isDark: boolean;
}

/**
 * Per-page backdrop plate presets (backdrop engine v2). Each page maps to a
 * fixed landscape contour plate split into TWO assets per theme:
 *   <page>_<theme>_plate.svg — static contours, painted as a CSS background.
 *   <page>_<theme>_glow.svg  — the animated comet system, fetched + inlined on
 *     top so its CSS motion-path sprites animate WITHOUT re-rasterizing the
 *     giant static plate every frame.
 *
 * Files are generated by scripts/build-plates.mjs into public/images/plates/.
 */
export type PlatePage =
  | 'home'
  | 'portfolio'
  | 'ej'
  | 'resume'
  | 'interests'
  | 'notFound';

const platePreset = (page: PlatePage) => {
  return {
    lightImage: `/images/plates/${page}_light_plate.svg`,
    darkImage: `/images/plates/${page}_dark_plate.svg`,
    glowLight: `/images/plates/${page}_light_glow.svg`,
    glowDark: `/images/plates/${page}_dark_glow.svg`,
  } as const;
};

export const PLATE_PRESETS = {
  home: platePreset('home'),
  portfolio: platePreset('portfolio'),
  ej: platePreset('ej'),
  resume: platePreset('resume'),
  interests: platePreset('interests'),
  notFound: platePreset('notFound'),
} as const;

/**
 * Hook for managing theme-aware backgrounds with mobile detection.
 */
export function useThemeBackground(options: ThemeBackgroundOptions): ThemeBackgroundResult {
  const { resolvedTheme } = useTheme();
  const [mounted, setMounted] = useState(false);
  const [isMobile, setIsMobile] = useState(false);

  const mobileBreakpoint = options.mobileBreakpoint ?? 768;

  useEffect(() => {
    setMounted(true);

    const checkMobile = () => {
      setIsMobile(window.innerWidth < mobileBreakpoint);
    };

    checkMobile();
    window.addEventListener('resize', checkMobile);

    return () => window.removeEventListener('resize', checkMobile);
  }, [mobileBreakpoint]);

  const isDark = mounted && resolvedTheme === 'dark';

  const plateSrc = useMemo(
    () => (!mounted ? options.lightImage : isDark ? options.darkImage : options.lightImage),
    [mounted, isDark, options.lightImage, options.darkImage],
  );

  const glowSrc = useMemo(
    () => (!mounted ? options.glowLight : isDark ? options.glowDark : options.glowLight),
    [mounted, isDark, options.glowLight, options.glowDark],
  );

  const backgroundImage = useMemo(() => `url(${plateSrc})`, [plateSrc]);

  return {
    mounted,
    isMobile,
    resolvedTheme,
    backgroundImage,
    plateSrc,
    glowSrc,
    isDark,
  };
}
